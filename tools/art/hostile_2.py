def tile(w, h, *motif):
    """A w x h grid filled by repeating the motif rows (cropped to fit)."""
    return [(motif[j % len(motif)] * (w // len(motif[0]) + 1))[:w] for j in range(h)]


def shade(hexcol, f):
    """Scale a #rrggbb colour by f (f > 1 lightens towards white)."""
    rgb = [int(hexcol[i:i + 2], 16) for i in (1, 3, 5)]
    if f <= 1:
        out = [round(c * f) for c in rgb]
    else:
        out = [round(c + (255 - c) * (f - 1)) for c in rgb]
    return "#" + "".join(f"{max(0, min(255, c)):02x}" for c in out)


